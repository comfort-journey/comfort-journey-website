/**
 * Filter keyword recommendations by destination or query
 */
export function getKeywordRecommendations(destinationOrQuery = '') {
  if (!destinationOrQuery || !destinationOrQuery.trim()) {
    return UBERSUGGEST_TRAVEL_KEYWORDS.slice(0, 15);
  }
  const q = destinationOrQuery.toLowerCase().trim();
  const matched = UBERSUGGEST_TRAVEL_KEYWORDS.filter(k => 
    k.destination.toLowerCase().includes(q) ||
    k.keyword.toLowerCase().includes(q) ||
    k.opportunity.toLowerCase().includes(q) ||
    k.intent.toLowerCase().includes(q)
  );

  return matched.length > 0 ? matched : UBERSUGGEST_TRAVEL_KEYWORDS.slice(0, 10);
}

/**
 * AI Auto-Optimization Generator: Creates Google #1 Meta Title, Meta Description,
 * Focus Keyword, and H2 Subheadings from Tour Package data and Ubersuggest Keywords.
 */
export function generateSmartSeoPlan(tourOrBlog = {}) {
  const name = tourOrBlog.name || tourOrBlog.title || 'Exclusive Tour Package';
  const location = tourOrBlog.location || tourOrBlog.destination || tourOrBlog.city || '';
  const duration = tourOrBlog.duration || (tourOrBlog.itinerary?.length ? `${tourOrBlog.itinerary.length} Days` : '5 Days');
  const price = tourOrBlog.price ? `₹${Number(tourOrBlog.price).toLocaleString('en-IN')}` : 'Best Price';

  // Find best matching high-volume, low-SD keyword
  const destMatch = getKeywordRecommendations(location || name);
  const bestKeyword = destMatch[0]?.keyword || `${location || name} tour package`;
  const secondaryKeyword = destMatch[1]?.keyword || `${duration} luxury ${location || 'holiday'}`;

  // 1. Google-Perfect Meta Title (Target: 50-60 characters)
  let metaTitle = `${name} (${duration}) | Comfort Journey`;
  if (metaTitle.length > 60) {
    metaTitle = `${name} | ${duration} Luxury Tour`;
  }
  if (metaTitle.length < 45 && location) {
    metaTitle = `${name} — ${location} Tour (${duration})`;
  }

  // 2. High-CTR Meta Description (Target: 145-160 characters with CTA)
  const metaDescription = `Book ${name} (${duration}) with Comfort Journey. Handcrafted itinerary, 4-star stays, private transfers & 24/7 concierge from ${price}. Reserve now!`;

  // 3. Recommended SEO Headings for Itinerary & Highlights
  const suggestedHeadings = [
    `Experience the Best of ${location || name} — Handcrafted ${duration} Itinerary`,
    `VIP Inclusions & Privileges Included with ${name}`,
    `Why Travelers Choose Comfort Journey for ${location || 'Luxury Holidays'}`
  ];

  // 4. LSI Keywords to weave into the package description
  const lsiKeywords = destMatch.slice(0, 5).map(k => k.keyword);

  return {
    metaTitle: metaTitle.slice(0, 65),
    metaDescription: metaDescription.slice(0, 160),
    focusKeyword: bestKeyword,
    secondaryKeyword,
    suggestedHeadings,
    lsiKeywords,
    targetSearchVolume: destMatch[0]?.volume || 14200,
    seoDifficulty: destMatch[0]?.sd || 22,
    cpc: destMatch[0]?.cpc || '₹32.50'
  };
}

/**
 * 1-Click CSV Parser for Ubersuggest exported CSVs
 * Works with "Keyword Ideas", "Rank Tracking", or "Site Audit" CSVs
 */
export function parseUbersuggestCsvText(csvText) {
  if (!csvText || typeof csvText !== 'string') return [];
  const lines = csvText.split(/\r?\n/).filter(line => line.trim().length > 0);
  if (lines.length < 2) return [];

  const headers = lines[0].split(',').map(h => h.replace(/["\r]/g, '').trim().toLowerCase());
  const keywordIdx = headers.findIndex(h => h.includes('keyword') || h.includes('query'));
  const volumeIdx = headers.findIndex(h => h.includes('volume') || h.includes('searches'));
  const cpcIdx = headers.findIndex(h => h.includes('cpc') || h.includes('cost'));
  const sdIdx = headers.findIndex(h => h.includes('sd') || h.includes('seo difficulty') || h.includes('difficulty'));

  const parsed = [];
  for (let i = 1; i < lines.length; i++) {
    const cols = lines[i].split(',').map(c => c.replace(/["\r]/g, '').trim());
    if (cols.length <= keywordIdx || !cols[keywordIdx]) continue;

    const keyword = cols[keywordIdx];
    const volume = volumeIdx !== -1 && cols[volumeIdx] ? Number(cols[volumeIdx].replace(/[^0-9]/g, '')) || 1000 : 1200;
    const cpc = cpcIdx !== -1 && cols[cpcIdx] ? (cols[cpcIdx].startsWith('₹') || cols[cpcIdx].startsWith('$') ? cols[cpcIdx] : `₹${cols[cpcIdx]}`) : '₹25.00';
    const sd = sdIdx !== -1 && cols[sdIdx] ? Number(cols[sdIdx].replace(/[^0-9]/g, '')) || 25 : 25;

    let opportunity = '🔥 High Volume Easy Win';
    if (sd < 20) opportunity = '⭐ Super Easy Win';
    else if (sd > 45) opportunity = '⚠️ Competitive';

    parsed.push({
      keyword,
      volume,
      cpc,
      sd,
      pd: 60,
      intent: 'Commercial',
      destination: 'Custom Import',
      opportunity
    });
  }

  return parsed;
}
