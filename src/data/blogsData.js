// Helper to get a blog by slug
export function getBlogBySlug(slug) {
  if (!slug) return null;
  const clean = slug.replace(/^#\/?/, '').replace(/^blog\/?/, '').toLowerCase().trim();
  return BLOGS_DATA.find(b => b.slug.toLowerCase() === clean || b.id.toLowerCase() === clean) || null;
}
